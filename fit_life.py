"""
FitLife - Консольный фитнес-бот
Помогает пользователям следить за здоровьем: рассчитывает ИМТ и норму воды
"""

# Константы для расчётов
WATER_PER_KG = 30          # мл воды на 1 кг веса
ML_TO_LITERS = 1000        # перевод миллилитров в литры


def main():
    """
    Основная функция программы.
    Последовательно выполняет все шаги взаимодействия с пользователем.
    """
    
    # Шаг 1: Знакомство с пользователем
    print("Добро пожаловать в FitLife! 👋")
    print("Я твой персональный фитнес-помощник!\n")
    
    # Запрос имени и возраста
    user_name = input("Как тебя зовут? ")
    user_age = int(input("Сколько тебе лет? "))
    
    print(f"\nПриятно познакомиться, {user_name}!")
    print("Теперь давай узнаем твои физические параметры.\n")
    
    # Шаг 2: Сбор параметров и расчёты
    # Запрос веса и роста
    user_weight = float(input("Введи свой вес (в кг): "))
    user_height = float(input("Введи свой рост (в метрах, например, 1.75): "))
    
    # Расчёт индекса массы тела (ИМТ)
    bmi = user_weight / (user_height ** 2)
    bmi_rounded = round(bmi, 1)
    
    # Расчёт нормы воды
    water_ml = user_weight * WATER_PER_KG
    water_l = water_ml / ML_TO_LITERS
    
    # Шаг 3: Вывод результата
    print("\n" + "=" * 40)
    print(f"Отчет для пользователя: {user_name} ({user_age} г.)")
    print(f"Твой Индекс Массы Тела: {bmi_rounded}")
    print(f"Рекомендуемая норма воды: {water_l:.1f} л. в день")
    print("=" * 40)
    print("\nРасчет окончен. Будьте здоровы! 🌟")


# Запуск программы
if __name__ == "__main__":
    main()
